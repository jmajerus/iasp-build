"""Tests for iasp_tooling.lib.snapshot_renderer."""

from datetime import datetime, timezone
from pathlib import Path
import sys

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from iasp_tooling.lib.snapshot_renderer import (
    SnapshotEntry,
    group_key_from_path,
    render_snapshot_markdown,
)


def test_group_key_from_path_variants():
    assert group_key_from_path(None) == "root"
    assert group_key_from_path("") == "root"
    assert group_key_from_path("chapters/part-one.md") == "chapters"
    assert group_key_from_path("preface.md") == "preface.md"


def test_render_snapshot_markdown_outputs_expected_structure():
    entries = [
        SnapshotEntry(
            label="Chapter One",
            group="part_one",
            index=1,
            path="parts/part-one.md",
            note="Manifest: `parts/part-one.json`",
            children=[
                SnapshotEntry(
                    label="Included Sidebar",
                    kind="include-file",
                    path="sidebars/warning.md",
                )
            ],
        )
    ]

    rendered = render_snapshot_markdown(
        entries,
        title="Test Snapshot",
        source_label="book-order.txt",
        profile="draft",
        timestamp=datetime(2025, 1, 1, tzinfo=timezone.utc),
    )

    expected = "\n".join(
        [
            "# Test Snapshot",
            "",
            "_Generated on 2025-01-01 00:00 UTC from `book-order.txt` for profile `draft`. Do not edit this file manually; rerun the generator instead._",
            "",
            "1. **Part One -> Chapter One**",
            "    - `parts/part-one.md`",
            "    - Manifest: `parts/part-one.json`",
            "    - **Included Sidebar**",
            "        - `sidebars/warning.md`",
            "",
        ]
    )

    assert rendered == expected

"""Render SnapshotEntry trees into Markdown."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Sequence

__all__ = [
    "SnapshotEntry",
    "group_key_from_path",
    "render_snapshot_markdown",
]


@dataclass
class SnapshotEntry:
    """Render-friendly representation of the canonical book order."""

    label: str
    path: str | None = None
    kind: str = "file"
    group: str | None = None
    index: int | None = None
    note: str | None = None
    children: list["SnapshotEntry"] = field(default_factory=list)


def group_key_from_path(rel_path: str | None) -> str:
    if not rel_path:
        return "root"
    prefix = rel_path.split("/", 1)[0]
    return prefix or "root"


def _format_group_label(raw: str) -> str:
    cleaned = raw.replace("_", " ").replace("-", " ").strip()
    if not cleaned:
        return "Root"
    return cleaned.title()


def _render_entry(entry: SnapshotEntry, depth: int, lines: list[str]) -> None:
    indent = "    " * depth

    if depth == 0:
        group_label = _format_group_label(entry.group or "")
        combined_label = f"{group_label} -> {entry.label}" if entry.group else entry.label
        lines.append(f"{entry.index}. **{combined_label}**")
    else:
        body = entry.label
        if entry.kind not in {"include-list-item"}:
            body = f"**{body}**"
        lines.append(f"{indent}- {body}")

    if entry.path:
        lines.append(f"{indent}    - `{entry.path}`")

    if entry.note:
        lines.append(f"{indent}    - {entry.note}")

    for child in entry.children:
        _render_entry(child, depth + 1, lines)


def render_snapshot_markdown(
    entries: Sequence[SnapshotEntry],
    *,
    title: str,
    source_label: str,
    profile: str | None = None,
    timestamp: datetime | None = None,
) -> str:
    """Render the collected snapshot entries into Markdown."""

    timestamp = timestamp or datetime.now(timezone.utc)
    meta = f"Generated on {timestamp.strftime('%Y-%m-%d %H:%M UTC')} from `{source_label}`"
    if profile:
        meta += f" for profile `{profile}`"
    meta += ". Do not edit this file manually; rerun the generator instead."

    lines: list[str] = [f"# {title}", "", f"_{meta}_", ""]

    for entry in entries:
        _render_entry(entry, 0, lines)
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"
